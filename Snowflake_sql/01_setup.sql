-- =========================================================

-- 1. Set role
USE ROLE SYSADMIN;

-- 2. Create database
CREATE DATABASE IF NOT EXISTS FUNNELVISION_DB;

-- 3. Create warehouse
CREATE WAREHOUSE IF NOT EXISTS FUNNELVISION_WH
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;

-- 4. Create RAW schema
CREATE SCHEMA IF NOT EXISTS FUNNELVISION_DB.RAW;

USE DATABASE FUNNELVISION_DB;
USE SCHEMA RAW;

-- 5. Create CSV file format
CREATE FILE FORMAT IF NOT EXISTS CSV_FORMAT
    TYPE = CSV
    FIELD_DELIMITER = ','
    SKIP_HEADER = 1
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    NULL_IF = ('', 'NULL', 'null')
    EMPTY_FIELD_AS_NULL = TRUE
    TRIM_SPACE = TRUE
    ERROR_ON_COLUMN_COUNT_MISMATCH = TRUE;

-- 6. Create internal stage
CREATE STAGE IF NOT EXISTS FUNNELVISION_STAGE
    FILE_FORMAT = CSV_FORMAT;

-- 7. Create RAW table: website sessions
CREATE TABLE IF NOT EXISTS WEBSITE_SESSIONS (
    WEBSITE_SESSION_ID NUMBER,
    CREATED_AT TIMESTAMP_NTZ,
    USER_ID NUMBER,
    IS_REPEAT_SESSION NUMBER,
    UTM_SOURCE VARCHAR,
    UTM_CAMPAIGN VARCHAR,
    UTM_CONTENT VARCHAR,
    DEVICE_TYPE VARCHAR,
    HTTP_REFERER VARCHAR
);

-- 8. Create RAW table: website pageviews
CREATE TABLE IF NOT EXISTS WEBSITE_PAGEVIEWS (
    WEBSITE_PAGEVIEW_ID NUMBER,
    CREATED_AT TIMESTAMP_NTZ,
    WEBSITE_SESSION_ID NUMBER,
    PAGEVIEW_URL VARCHAR
);

-- 9. Create RAW table: orders
CREATE TABLE IF NOT EXISTS ORDERS (
    ORDER_ID NUMBER,
    CREATED_AT TIMESTAMP_NTZ,
    WEBSITE_SESSION_ID NUMBER,
    USER_ID NUMBER,
    PRIMARY_PRODUCT_ID NUMBER,
    ITEMS_PURCHASED NUMBER,
    PRICE_USD NUMBER(12,2),
    COGS_USD NUMBER(12,2)
);

-- 10. Create RAW table: order items
CREATE TABLE IF NOT EXISTS ORDER_ITEMS (
    ORDER_ITEM_ID NUMBER,
    CREATED_AT TIMESTAMP_NTZ,
    ORDER_ID NUMBER,
    PRODUCT_ID NUMBER,
    IS_PRIMARY_ITEM NUMBER,
    PRICE_USD NUMBER(12,2),
    COGS_USD NUMBER(12,2)
);

-- 11. Create RAW table: order item refunds
CREATE TABLE IF NOT EXISTS ORDER_ITEM_REFUNDS (
    ORDER_ITEM_REFUND_ID NUMBER,
    CREATED_AT TIMESTAMP_NTZ,
    ORDER_ITEM_ID NUMBER,
    ORDER_ID NUMBER,
    REFUND_AMOUNT_USD NUMBER(12,2)
);

-- 12. Create RAW table: products
CREATE TABLE IF NOT EXISTS PRODUCTS (
    PRODUCT_ID NUMBER,
    CREATED_AT TIMESTAMP_NTZ,
    PRODUCT_NAME VARCHAR
);

-- 13. Create RAW table: data dictionary
CREATE TABLE IF NOT EXISTS MAVEN_FUZZY_FACTORY_DATA_DICTIONARY (
    TABLE_NAME VARCHAR,
    FIELD VARCHAR,
    DESCRIPTION VARCHAR
);

-- 14. Create staging tables
-- These mirror their respective RAW table structures.
CREATE TABLE IF NOT EXISTS WEBSITE_SESSIONS_STG
    LIKE WEBSITE_SESSIONS;

CREATE TABLE IF NOT EXISTS WEBSITE_PAGEVIEWS_STG
    LIKE WEBSITE_PAGEVIEWS;

CREATE TABLE IF NOT EXISTS ORDERS_STG
    LIKE ORDERS;

CREATE TABLE IF NOT EXISTS ORDER_ITEMS_STG
    LIKE ORDER_ITEMS;

CREATE TABLE IF NOT EXISTS ORDER_ITEM_REFUNDS_STG
    LIKE ORDER_ITEM_REFUNDS;

CREATE TABLE IF NOT EXISTS PRODUCTS_STG
    LIKE PRODUCTS;

-- 15. Verify setup
SHOW WAREHOUSES LIKE 'FUNNELVISION_WH';
SHOW SCHEMAS IN DATABASE FUNNELVISION_DB;
SHOW FILE FORMATS IN SCHEMA FUNNELVISION_DB.RAW;
SHOW STAGES IN SCHEMA FUNNELVISION_DB.RAW;
SHOW TABLES IN SCHEMA FUNNELVISION_DB.RAW;
